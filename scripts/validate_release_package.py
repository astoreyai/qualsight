class ReleasePackageValidationError(ValueError):
    """Raised when extracted package bytes exceed or weaken the release boundary."""


def _validate_policy_minimum(policy: dict[str, Any]) -> None:
    forbidden_artifact_sha256s = policy.get("source_archive_forbidden_artifact_sha256s")
    if (
        policy.get("schema_version") != "1.0"
        or policy.get("policy_id") != "qualsight-controlled-workstation-beta-release-v1"
        or policy.get("source_archive_secret_scan") is not True
        or not REQUIRED_EXCLUSIONS.issubset(
            set(policy.get("source_archive_excluded_paths", ()))
        )
        or not REQUIRED_FORBIDDEN_SUFFIXES.issubset(
            set(policy.get("source_archive_forbidden_suffixes", ()))
        )
        or not isinstance(forbidden_artifact_sha256s, list)
        or not forbidden_artifact_sha256s
        or len(forbidden_artifact_sha256s) != len(set(forbidden_artifact_sha256s))
        or any(
            not isinstance(value, str) or SHA256_RE.fullmatch(value) is None
            for value in forbidden_artifact_sha256s
        )
        or not REQUIRED_FORBIDDEN_NAMES.issubset(
            set(policy.get("source_archive_forbidden_names", ()))
        )
        or ".env." not in set(policy.get("source_archive_forbidden_name_prefixes", ()))
        or "screenshot" not in set(policy.get("source_archive_forbidden_path_terms", ()))
        or not REQUIRED_CONTENT_TERMS.issubset(
            set(policy.get("source_archive_forbidden_content_terms", ()))
        )
        or policy.get("source_archive_reference_home_projection")
        != "/opt/qualsight/" + "external"
        or policy.get("source_archive_reference_projects_projection")
        != "/opt/qualsight/" + "external/projects"
        or set(policy.get("source_archive_reference_projects_files", ()))
        != EXPECTED_PROJECT_LOCATOR_FILES
        or policy.get("source_archive_reference_uv_command") != "uv"
        or set(policy.get("source_archive_reference_uv_files", ()))
        != EXPECTED_REFERENCE_UV_FILES
    ):
        raise ReleasePackageValidationError("release package policy minimum differs")
    observed_json = {
        path: set(values)
        for path, values in policy.get(
            "source_archive_controlled_locator_json_fields", {}
        ).items()
    }
    observed_text = {
        path: set(values)
        for path, values in policy.get(
            "source_archive_controlled_locator_text_suffixes", {}
        ).items()
    }
    if (
        observed_json != EXPECTED_LOCATOR_JSON_FIELDS
        or observed_text != EXPECTED_LOCATOR_TEXT_SUFFIXES
        or set(policy.get("source_archive_controlled_locator_files", ()))
        != {*EXPECTED_LOCATOR_JSON_FIELDS, *EXPECTED_LOCATOR_TEXT_SUFFIXES}
    ):
        raise ReleasePackageValidationError("release package policy minimum locator controls differ")


def _validate_registered_restricted_policy(
    package_files: dict[str, tuple[bytes, int]], policy: dict[str, Any]
) -> None:
    registry = _load_package_json(package_files, Path("resources/resource-registry.json"))
    resources = registry.get("resources") if isinstance(registry, dict) else None
    if not isinstance(resources, list):
        raise ReleasePackageValidationError("resource registry has no resource list")
    expected: set[str] = set()
    for resource in resources:
        if not isinstance(resource, dict):
            raise ReleasePackageValidationError("resource registry entry is not an object")
        artifacts = resource.get("artifacts", [])
        if not isinstance(artifacts, list):
            raise ReleasePackageValidationError("resource registry artifacts are not a list")
        for artifact in artifacts:
            if not isinstance(artifact, dict):
                raise ReleasePackageValidationError("resource registry artifact is not an object")
            if artifact.get("role") not in {"MODEL", "EXECUTABLE", "CONFIG"}:
                continue
            sha256 = artifact.get("sha256")
            if not isinstance(sha256, str) or SHA256_RE.fullmatch(sha256) is None:
                raise ReleasePackageValidationError(
                    "registered restricted artifact identity is invalid"
                )
            expected.add(sha256)
    observed = set(policy["source_archive_forbidden_artifact_sha256s"])
    if not expected or observed != expected:
        raise ReleasePackageValidationError(
            "registered restricted artifact identities differ from the release policy"
        )


def _load_json(path: Path) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
        raise ReleasePackageValidationError(f"cannot read release JSON {path}: {error}") from error


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _load_package_json(
    package_files: dict[str, tuple[bytes, int]], relative: Path
) -> Any:
    try:
        body = package_files[relative.as_posix()][0]
        return json.loads(body.decode("utf-8"))
    except (KeyError, UnicodeDecodeError, json.JSONDecodeError) as error:
        raise ReleasePackageValidationError(
            f"cannot read release JSON {relative}: {error}"
        ) from error


def _stable_identity(observed: os.stat_result) -> tuple[int, int, int, int, int, int]:
    return (
        observed.st_dev,
        observed.st_ino,
        observed.st_mode,
        observed.st_size,
        observed.st_mtime_ns,
        observed.st_ctime_ns,
    )


def _read_open_regular_file(
    directory_fd: int,
    name: str,
    relative: PurePosixPath,
    probed: os.stat_result,
) -> tuple[bytes, int]:
    flags = os.O_RDONLY | os.O_CLOEXEC | os.O_NOFOLLOW
    descriptor = os.open(name, flags, dir_fd=directory_fd)
    try:
        before = os.fstat(descriptor)
        if (
            _stable_identity(probed) != _stable_identity(before)
            or not stat.S_ISREG(before.st_mode)
        ):
            raise ReleasePackageValidationError(
                f"package member changed while opening: {relative}"
            )
        mode = stat.S_IMODE(before.st_mode)
        if (
            mode & 0o7022
            or mode & 0o700 not in {0o600, 0o700}
        ):
            raise ReleasePackageValidationError(
                f"package contents manifest unsafe package file mode: {relative}"
            )
        chunks: list[bytes] = []
        while True:
            chunk = os.read(descriptor, 1024 * 1024)
            if not chunk:
                break
            chunks.append(chunk)
        after = os.fstat(descriptor)
        body = b"".join(chunks)
        if _stable_identity(before) != _stable_identity(after) or len(body) != before.st_size:
            raise ReleasePackageValidationError(
                f"package member changed while reading: {relative}"
            )
        return body, mode
    finally:
        os.close(descriptor)


def _validate_directory_mode(relative: PurePosixPath, observed: os.stat_result) -> None:
    mode = stat.S_IMODE(observed.st_mode)
    if mode & ~0o755 or mode & 0o700 != 0o700:
        label = relative.as_posix() if relative.parts else "."
        raise ReleasePackageValidationError(
            f"package contents manifest unsafe package directory mode: {label}"
        )


def _snapshot_package_tree(root: Path) -> dict[str, tuple[bytes, int]]:
    directory_flags = os.O_RDONLY | os.O_CLOEXEC | os.O_NOFOLLOW | os.O_DIRECTORY
    root_descriptor = os.open(root, directory_flags)
    package_files: dict[str, tuple[bytes, int]] = {}

    def walk(directory_fd: int, prefix: PurePosixPath) -> None:
        before = os.fstat(directory_fd)
        if not stat.S_ISDIR(before.st_mode):
            raise ReleasePackageValidationError(
                f"package member is not a directory: {prefix.as_posix()}"
            )
        _validate_directory_mode(prefix, before)
        try:
            names = sorted(os.listdir(directory_fd))
        except OSError as error:
            raise ReleasePackageValidationError(
                f"cannot enumerate package directory: {prefix.as_posix()}"
            ) from error
        for name in names:
            if not name or name in {".", ".."} or "/" in name or "\\" in name:
                raise ReleasePackageValidationError("package member name is unsafe")
            relative = prefix / name if prefix.parts else PurePosixPath(name)
            probed = os.stat(name, dir_fd=directory_fd, follow_symlinks=False)
            if stat.S_ISDIR(probed.st_mode):
                child_descriptor = os.open(name, directory_flags, dir_fd=directory_fd)
                try:
                    opened = os.fstat(child_descriptor)
                    if _stable_identity(probed) != _stable_identity(opened):
                        raise ReleasePackageValidationError(
                            f"package directory changed while opening: {relative}"
                        )
                    walk(child_descriptor, relative)
                finally:
                    os.close(child_descriptor)
            elif stat.S_ISREG(probed.st_mode):
                package_files[relative.as_posix()] = _read_open_regular_file(
                    directory_fd,
                    name,
                    relative,
                    probed,
                )
            elif stat.S_ISLNK(probed.st_mode):
                raise ReleasePackageValidationError(
                    f"package contains a symbolic link: {relative}"
                )
            else:
                raise ReleasePackageValidationError(
                    f"package contains a non-regular member: {relative}"
                )
        after = os.fstat(directory_fd)
        if _stable_identity(before) != _stable_identity(after):
            raise ReleasePackageValidationError(
                f"package directory changed while reading: {prefix.as_posix()}"
            )

    try:
        walk(root_descriptor, PurePosixPath())
    finally:
        os.close(root_descriptor)
    return package_files


def _source_archive_boundary() -> Any:
    path = Path(__file__).resolve().with_name("create_release_source_archive.py")
    module = types.ModuleType("qualsight_release_source_boundary")
    module.__file__ = str(path)
    try:
        source = path.read_bytes()
        exec(compile(source, str(path), "exec"), module.__dict__)
    except (OSError, SyntaxError, ImportError) as error:
        raise ReleasePackageValidationError(
            "source archive release boundary is unavailable"
        ) from error
    return module


def _exact_file(root: Path, relative: Path) -> Path:
    path = root / relative
    try:
        observed = path.lstat()
    except OSError as error:
        raise ReleasePackageValidationError(f"required package file is absent: {relative}") from error
    if path.is_symlink() or not path.is_file() or observed.st_size < 1:
        raise ReleasePackageValidationError(f"required package member is not a regular file: {relative}")
    return path


def _validate_package_contents_manifest(
    root: Path, *, expected_commit: str | None = None
) -> tuple[dict[str, Any], dict[str, tuple[bytes, int]]]:
    package_files = _snapshot_package_tree(root)
    try:
        manifest_body, manifest_mode = package_files[PACKAGE_CONTENTS.as_posix()]
        manifest = json.loads(manifest_body.decode("utf-8"))
    except (KeyError, UnicodeDecodeError, json.JSONDecodeError) as error:
        raise ReleasePackageValidationError(
            "cannot read package contents manifest"
        ) from error
    if manifest_mode & ~0o644 or manifest_mode & 0o700 != 0o600:
        raise ReleasePackageValidationError("package contents manifest mode differs")
    if not isinstance(manifest, dict) or set(manifest) != {
        "schema_version",
        "source_commit",
        "files",
    }:
        raise ReleasePackageValidationError("package contents manifest shape differs")
    if (
        manifest["schema_version"] != "qualsight-source-package-contents-v1"
        or not isinstance(manifest["source_commit"], str)
        or re.fullmatch(r"[0-9a-f]{40}", manifest["source_commit"]) is None
        or not isinstance(manifest["files"], list)
        or not manifest["files"]
    ):
        raise ReleasePackageValidationError("package contents manifest authority differs")
    if expected_commit is not None:
        if re.fullmatch(r"[0-9a-f]{40}", expected_commit) is None:
            raise ReleasePackageValidationError("expected source commit is invalid")
        if manifest["source_commit"] != expected_commit:
            raise ReleasePackageValidationError("package source commit differs")

    expected_paths: list[str] = []
    for index, entry in enumerate(manifest["files"]):
        if not isinstance(entry, dict) or set(entry) != {
            "path",
            "sha256",
            "size_bytes",
            "unix_mode",
        }:
            raise ReleasePackageValidationError(
                f"package contents manifest entry {index} shape differs"
            )
        relative_text = entry["path"]
        if not isinstance(relative_text, str):
            raise ReleasePackageValidationError(
                f"package contents manifest entry {index} path is invalid"
            )
        relative = PurePosixPath(relative_text)
        if (
            not relative.parts
            or relative.is_absolute()
            or ".." in relative.parts
            or "\\" in relative_text
            or relative == PurePosixPath(PACKAGE_CONTENTS.as_posix())
            or relative.as_posix() != relative_text
        ):
            raise ReleasePackageValidationError(
                f"package contents manifest entry {index} path is invalid"
            )
        if (
            not isinstance(entry["sha256"], str)
            or SHA256_RE.fullmatch(entry["sha256"]) is None
            or not isinstance(entry["size_bytes"], int)
            or isinstance(entry["size_bytes"], bool)
            or entry["size_bytes"] < 0
            or entry["unix_mode"] not in {"0644", "0755"}
        ):
            raise ReleasePackageValidationError(
                f"package contents manifest entry {index} identity is invalid"
            )
        expected_paths.append(relative_text)

    if expected_paths != sorted(expected_paths) or len(expected_paths) != len(
        set(expected_paths)
    ):
        raise ReleasePackageValidationError(
            "package contents manifest paths are not unique and sorted"
        )
    observed_paths = sorted(
        path for path in package_files if path != PACKAGE_CONTENTS.as_posix()
    )
    if observed_paths != expected_paths:
        raise ReleasePackageValidationError(
            "package contents manifest membership differs"
        )
    for entry in manifest["files"]:
        body, mode = package_files[entry["path"]]
        declared_mode = int(entry["unix_mode"], 8)
        if (
            len(body) != entry["size_bytes"]
            or hashlib.sha256(body).hexdigest() != entry["sha256"]
            or mode & ~declared_mode
            or mode & 0o700 != declared_mode & 0o700
        ):
            raise ReleasePackageValidationError(
                f"package contents manifest identity differs: {entry['path']}"
            )
    return (
        {
            "source_commit": manifest["source_commit"],
            "manifest_files": len(expected_paths),
            "manifest_sha256": hashlib.sha256(manifest_body).hexdigest(),
        },
        package_files,
    )


def _locator_json_fields(value: Any, locator: str, pointer: str = "") -> set[str]:
    fields: set[str] = set()
    if isinstance(value, dict):
        for key, child in value.items():
            escaped = str(key).replace("~", "~0").replace("/", "~1")
            fields.update(_locator_json_fields(child, locator, f"{pointer}/{escaped}"))
    elif isinstance(value, list):
        for index, child in enumerate(value):
            fields.update(_locator_json_fields(child, locator, f"{pointer}/{index}"))
    elif isinstance(value, str) and locator in value:
        fields.add(pointer)
    return fields


def _validate_controlled_locator(
    *, relative: str, body: bytes, locator: bytes, policy: dict[str, Any]
) -> None:
    if locator not in body:
        return
    if relative == POLICY.as_posix():
        return
    json_fields = policy["source_archive_controlled_locator_json_fields"]
    text_suffixes = policy["source_archive_controlled_locator_text_suffixes"]
    if relative in json_fields:
        actual = _locator_json_fields(json.loads(body), locator.decode("utf-8"))
        expected = set(json_fields[relative])
        if actual != expected:
            raise ReleasePackageValidationError(
                f"controlled locator differs from its exact field allowlist in {relative}: "
                f"expected {sorted(expected)}, observed {sorted(actual)}"
            )
        return
    if relative in text_suffixes:
        remaining = body
        for suffix in text_suffixes[relative]:
            target = locator + suffix.encode("utf-8")
            if remaining.count(target) != 1:
                raise ReleasePackageValidationError(
                    f"controlled locator differs from its exact value allowlist in {relative}"
                )
            remaining = remaining.replace(target, b"")
        if locator in remaining:
            raise ReleasePackageValidationError(
                f"controlled locator exceeds its exact value allowlist in {relative}"
            )
        return
    raise ReleasePackageValidationError(
        f"controlled locator appears outside the exact field allowlist: {relative}"
    )


def _validate_package_tree(
    package_files: dict[str, tuple[bytes, int]], policy: dict[str, Any]
) -> tuple[int, int]:
    for relative in policy["source_archive_excluded_paths"]:
        if relative in package_files or any(
            path.startswith(f"{relative}/") for path in package_files
        ):
            raise ReleasePackageValidationError(f"excluded package path is present: {relative}")

    source_boundary = _source_archive_boundary()
    registered_restricted = set(policy["source_archive_forbidden_artifact_sha256s"])
    locator = policy["source_archive_reference_home_projection"].encode("utf-8")
    projects_locator = policy["source_archive_reference_projects_projection"].encode(
        "utf-8"
    )
    project_locator_files = set(policy["source_archive_reference_projects_files"])
    files = 0
    total_bytes = 0
    for relative in sorted(package_files):
        pure = PurePosixPath(relative)
        body = package_files[relative][0]
        if hashlib.sha256(body).hexdigest() in registered_restricted:
            raise ReleasePackageValidationError(
                f"forbidden release content registered restricted artifact: {relative}"
            )
        try:
            source_boundary._validate_regular_body(
                relative=pure,
                body=body,
                policy=policy,
            )
        except ValueError as error:
            raise ReleasePackageValidationError(str(error)) from error
        body_without_project_locator = body
        if projects_locator in body and relative != POLICY.as_posix():
            if relative not in project_locator_files:
                raise ReleasePackageValidationError(
                    "controlled project locator appears outside the exact file "
                    f"allowlist: {relative}"
                )
            body_without_project_locator = body.replace(projects_locator, b"")
        _validate_controlled_locator(
            relative=relative,
            body=body_without_project_locator,
            locator=locator,
            policy=policy,
        )
        files += 1
        total_bytes += len(body)
    return files, total_bytes


PRIVATE_BUILD_PATH_PATTERN = re.compile(
    rb"(?i)(?:"
    rb"file:(?:/{2,3}|%2f%2f)|"
    rb"/(?:home|mnt|tmp)/|"
    rb"%2f(?:home|mnt|tmp)%2f|"
    rb"\\u002f(?:home|mnt|tmp)\\u002f|"
    rb"[A-Z]:[\\/]{1,2}(?:Users|Documents|AppData)[\\/]{1,2}"
    rb")"
)


def validate_console_dist(root: Path) -> dict[str, int | str]:
    root = root.resolve(strict=True)
    if not root.is_dir():
        raise ReleasePackageValidationError("console distribution root is not a directory")
    files = 0
    total_bytes = 0
    for path in sorted(root.rglob("*")):
        relative = path.relative_to(root).as_posix()
        mode = path.stat(follow_symlinks=False).st_mode
        if stat.S_ISDIR(mode):
            continue
        if not stat.S_ISREG(mode):
            raise ReleasePackageValidationError(
                f"console distribution contains a non-regular member: {relative}"
            )
        if path.suffix.casefold() == ".map":
            raise ReleasePackageValidationError(
                f"console distribution contains a source map: {relative}"
            )
        body = path.read_bytes()
        if PRIVATE_BUILD_PATH_PATTERN.search(body):
            raise ReleasePackageValidationError(
                f"console distribution contains a private build path: {relative}"
            )
        files += 1
        total_bytes += len(body)
    if files == 0:
        raise ReleasePackageValidationError("console distribution is empty")
    return {
        "schema_version": "qualsight-release-console-validation-v1",
        "regular_files": files,
        "total_bytes": total_bytes,
    }


def validate_release_sidecars(
    paths: list[Path], *, policy_path: Path
) -> dict[str, int | str]:
    if not paths:
        raise ReleasePackageValidationError("release sidecar list is empty")
    policy = _load_json(policy_path.resolve(strict=True))
    _validate_policy_minimum(policy)
    source_boundary = _source_archive_boundary()
    files = 0
    total_bytes = 0
    seen: set[Path] = set()
    for path in paths:
        resolved = path.resolve(strict=True)
        if resolved in seen:
            raise ReleasePackageValidationError(
                f"release sidecar is repeated: {path.name}"
            )
        seen.add(resolved)
        mode = path.stat(follow_symlinks=False).st_mode
        if not stat.S_ISREG(mode) or path.is_symlink():
            raise ReleasePackageValidationError(
                f"release sidecar is not a regular file: {path.name}"
            )
        body = path.read_bytes()
        try:
            source_boundary._validate_regular_body(
                relative=PurePosixPath(path.name),
                body=body,
                policy=policy,
            )
        except ValueError as error:
            raise ReleasePackageValidationError(str(error)) from error
        if PRIVATE_BUILD_PATH_PATTERN.search(body):
            raise ReleasePackageValidationError(
                f"release sidecar contains a private build path: {path.name}"
            )
        files += 1
        total_bytes += len(body)
    return {
        "schema_version": "qualsight-release-sidecar-validation-v1",
        "regular_files": files,
        "total_bytes": total_bytes,
    }


def _package_text(
    package_files: dict[str, tuple[bytes, int]], relative: Path
) -> str:
    try:
        return package_files[relative.as_posix()][0].decode("utf-8")
    except (KeyError, UnicodeDecodeError) as error:
        raise ReleasePackageValidationError(
            f"cannot read release text {relative}: {error}"
        ) from error


def _validate_versions(package_files: dict[str, tuple[bytes, int]]) -> str:
    backend = tomllib.loads(_package_text(package_files, Path("backend/pyproject.toml")))[
        "project"
    ]["version"]
    root_npm = _load_package_json(package_files, Path("package.json"))["version"]
    frontend_npm = _load_package_json(package_files, Path("frontend/package.json"))["version"]
    match = re.fullmatch(r"(\d+\.\d+\.\d+)b(\d+)", backend)
    if match is None:
        raise ReleasePackageValidationError("backend version is not a beta release")
    expected_npm = f"{match.group(1)}-beta.{match.group(2)}"
    if root_npm != expected_npm or frontend_npm != expected_npm:
        raise ReleasePackageValidationError("Python and npm package versions differ")
    workspace_python = tomllib.loads(
        _package_text(package_files, Path("pyproject.toml"))
    )["project"]["version"]
    if workspace_python != match.group(1):
        raise ReleasePackageValidationError("workspace Python base version differs")
    locked_packages = {
        item["name"]: item["version"]
        for item in tomllib.loads(_package_text(package_files, Path("uv.lock")))[
            "package"
        ]
        if item.get("name") in {"qualsight-backend", "qualsight-workspace"}
    }
    if locked_packages != {
        "qualsight-backend": backend,
        "qualsight-workspace": workspace_python,
    }:
        raise ReleasePackageValidationError("uv.lock package versions differ")
    return backend


def _pinned_https(record: dict[str, Any], *, location: str) -> None:
    url = record.get("url")
    sha256 = record.get("sha256")
    size = record.get("size_bytes")
    if (
        not isinstance(url, str)
        or urlsplit(url).scheme != "https"
        or not isinstance(sha256, str)
        or SHA256_RE.fullmatch(sha256) is None
        or not isinstance(size, int)
        or size < 1
    ):
        raise ReleasePackageValidationError(f"{location} lost its exact HTTPS/hash/size pin")


def _validate_acquisition_contract(
    package_files: dict[str, tuple[bytes, int]]
) -> dict[str, int]:
    summary_body = package_files[SUMMARY.as_posix()][0]
    summary = _load_package_json(package_files, SUMMARY)
    if (
        summary.get("schema_version") != "1.0.0"
        or summary.get("report_id") != "qualsight-addon-acquisition-public-summary-v1"
        or summary.get("distribution_boundary")
        != "CONTROLLED_SINGLE_USER_WORKSTATION_NON_PORTABLE"
    ):
        raise ReleasePackageValidationError("release evidence summary boundary differs")
    if summary.get("authority") != {
        "artifact_identity_authority": False,
        "identity_only": True,
        "rights_authority": False,
        "runtime_authority": False,
    }:
        raise ReleasePackageValidationError("release evidence summary claims authority")
    if summary.get("acquisition_contract") != EXPECTED_ACQUISITION_CONTRACT:
        raise ReleasePackageValidationError("release evidence acquisition contract differs")
    observed_evidence_identities = {
        (
            entry.get("repository_relative_path"),
            entry.get("sha256"),
            entry.get("size_bytes"),
        )
        for entry in summary.get("original_evidence_identities", ())
        if isinstance(entry, dict)
    }
    if observed_evidence_identities != EXPECTED_OMITTED_EVIDENCE_IDENTITIES:
        raise ReleasePackageValidationError("release summary full-hash identities differ")
    locator_projection = summary.get("controlled_locator_projection")
    if (
        not isinstance(locator_projection, dict)
        or locator_projection.get("package_prefix") != "/opt/qualsight/" + "external"
        or locator_projection.get("runtime_binding_required") is not True
        or locator_projection.get("environment_variable") != "QUALSIGHT_REGISTRY_PATH"
    ):
        raise ReleasePackageValidationError("release summary controlled-host binding differs")
    summary_sha256 = hashlib.sha256(summary_body).hexdigest()
    summary_size = len(summary_body)

    registry = _load_package_json(package_files, Path("resources/resource-registry.json"))
    resource_ids = {item["resource_id"] for item in registry["resources"]}
    if len(resource_ids) != len(registry["resources"]):
        raise ReleasePackageValidationError("resource registry contains duplicate IDs")

    checkpoints = _load_package_json(package_files, CHECKPOINTS)
    for index, entry in enumerate(checkpoints["entries"]):
        if entry["resource_id"] not in resource_ids:
            raise ReleasePackageValidationError("checkpoint is absent from the resource registry")
        if (
            not entry["admission_state"].startswith("ADMITTED_LOCAL_")
            or entry["third_party_rights_status"] == "UNRESOLVED"
        ):
            raise ReleasePackageValidationError("checkpoint rights gate is not terminal")
        evidence = entry["published_evidence"]
        if (
            evidence["repository_relative_path"] != SUMMARY.as_posix()
            or evidence["artifact_sha256"] != summary_sha256
            or evidence["artifact_size_bytes"] != summary_size
            or "does not verify rights" not in evidence["resolution_note"]
        ):
            raise ReleasePackageValidationError("checkpoint evidence was not safely projected")
        _pinned_https(entry["source"] | entry["artifact"], location=f"checkpoint[{index}]")

    datasets = _load_package_json(package_files, DATASETS)
    archive = datasets["archive"]
    if (
        archive["evidence_path"] != SUMMARY.as_posix()
        or archive["evidence_sha256"] != summary_sha256
        or "does not verify rights" not in datasets["policy"]
    ):
        raise ReleasePackageValidationError("dataset evidence was not safely projected")
    _pinned_https(archive, location="verification dataset")
    dataset_addon_ids = [protocol["addon_id"] for protocol in datasets["protocols"]]
    if len(dataset_addon_ids) != len(set(dataset_addon_ids)) or any(
        not addon_id for addon_id in dataset_addon_ids
    ):
        raise ReleasePackageValidationError("verification protocol add-on IDs differ")

    upstream = _load_package_json(package_files, UPSTREAM)
    for index, source in enumerate(upstream["sources"]):
        _pinned_https(source, location=f"upstream source[{index}]")
        if not source["license_note"].startswith(
            "CONTROLLED_HOST_CLAIM_NOT_VERIFIED_BY_PACKAGE_SUMMARY:"
        ):
            raise ReleasePackageValidationError("upstream rights claim was not degraded")
        if "resources/upstream/" in source["license_note"]:
            raise ReleasePackageValidationError("upstream manifest depends on omitted evidence")
    return {
        "checkpoint_entries": len(checkpoints["entries"]),
        "dataset_protocols": len(datasets["protocols"]),
        "upstream_sources": len(upstream["sources"]),
    }


def validate_release_package(
    root: Path, *, expected_commit: str | None = None
) -> dict[str, Any]:
    root = root.resolve(strict=True)
    contents, package_files = _validate_package_contents_manifest(
        root,
        expected_commit=expected_commit,
    )
    for relative in REQUIRED_FILES:
        member = package_files.get(relative.as_posix())
        if member is None:
            raise ReleasePackageValidationError(f"required package file is absent: {relative}")
        if not member[0]:
            raise ReleasePackageValidationError(
                f"required package member is not a regular file: {relative}"
            )
    policy = _load_package_json(package_files, POLICY)
    _validate_policy_minimum(policy)
    _validate_registered_restricted_policy(package_files, policy)
    version = _validate_versions(package_files)
    acquisition = _validate_acquisition_contract(package_files)
    files, total_bytes = _validate_package_tree(package_files, policy)
    return {
        "schema_version": "qualsight-release-package-validation-v1",
        "status": "PASS",
        "version": version,
        "policy_id": policy["policy_id"],
        "regular_files": files,
        "total_bytes": total_bytes,
        **contents,
        **acquisition,
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    target = parser.add_mutually_exclusive_group(required=True)
    target.add_argument("--root", type=Path)
    target.add_argument("--console-root", type=Path)
    target.add_argument("--sidecar", action="append", type=Path)
    parser.add_argument("--policy", type=Path, default=POLICY)
    parser.add_argument("--expected-commit")
    args = parser.parse_args()
    try:
        if args.sidecar is not None:
            result = validate_release_sidecars(args.sidecar, policy_path=args.policy)
        elif args.console_root is not None:
            result = validate_console_dist(args.console_root)
        else:
            result = validate_release_package(
                args.root,
                expected_commit=args.expected_commit,
            )
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"RELEASE_PACKAGE_INVALID {error}")
        return 2
    print("RELEASE_PACKAGE_VALID " + json.dumps(result, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
